def stock_agent_prompt_config(config: dict) -> dict:
    """只拆分逐字匹配的旧内置提示词，保留用户自定义文本和显式留空的回退选择。"""
    leader = config.get("kind") == "leader"
    legacy = LEADER_PROMPT if leader else CUSTOM_PROMPT
    if config.get("prompt") == legacy and not any(
        key in config for key in ("common_prompt", "premarket_prompt", "review_prompt")
    ):
        return {**config, **(LEADER_PHASE_PROMPTS if leader else CUSTOM_PHASE_PROMPTS)}
    return config

